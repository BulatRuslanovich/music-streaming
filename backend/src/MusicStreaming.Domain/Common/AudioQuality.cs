namespace MusicStreaming.Domain.Common;

/// <summary>
/// Профиль качества, которым клиент оперирует вместо кодеков и битрейтов. Что именно стоит за
/// каждой ступенью, знает только сервер — см. <c>AudioProfiles</c> в слое приложения.
///
/// <para>
/// Значения хранятся в настройках пользователя, поэтому их нельзя переупорядочивать — только
/// дописывать. Порядок задан как лестница от самого экономного к самому качественному, так что
/// сравнение профилей между собой осмысленно.
/// </para>
/// </summary>
public enum AudioQuality
{
    Low = 0,
    Normal = 1,
    High = 2,

    /// <summary>Исходный файл без перекодирования — единственная ступень, играющая в любом браузере.</summary>
    Original = 3,
}
