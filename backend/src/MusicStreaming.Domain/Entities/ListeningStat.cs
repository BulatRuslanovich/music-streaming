namespace MusicStreaming.Domain.Entities;

/// <summary>
/// Сколько пользователь слушал один трек в течение одного часа.
///
/// <para>
/// Сводка существует потому, что ни один из уже имеющихся источников не отвечает на вопросы
/// статистики. <see cref="ListeningHistoryEntry"/> переписывает свою строку внутри получаса и
/// подрезается до последней тысячи записей, поэтому по нему нельзя посчитать ни повторы, ни
/// прошлый год. Журнал событий знает настоящие секунды, но чистится по сроку хранения. Аффинити
/// живёт вечно, но не помнит, когда именно слушали.
/// </para>
///
/// <para>
/// Час — самая крупная гранулярность, из которой ещё выводится активность по часам суток, и
/// достаточно мелкая, чтобы <c>AT TIME ZONE</c> развернул её в местные сутки любого пояса.
/// Заполняется тем же роллапом, что и аффинити, из тех же событий и под тем же watermark.
/// </para>
/// </summary>
public class ListeningStat
{
    public Guid UserId { get; set; }
    public User? User { get; set; }

    /// <summary>Начало часа в UTC, к которому отнесено прослушивание.</summary>
    public DateTimeOffset Hour { get; set; }

    public Guid TrackId { get; set; }
    public Track? Track { get; set; }

    /// <summary>Сколько прослушиваний трека началось в этот час.</summary>
    public int PlayCount { get; set; }

    /// <summary>Реально прослушанные секунды — перемотка и пауза не засчитаны.</summary>
    public long ListenedSeconds { get; set; }
}
