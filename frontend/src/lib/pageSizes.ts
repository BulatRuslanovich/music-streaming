/**
 * Размеры страниц списков — в одном месте.
 *
 * Раньше это число было продублировано в пяти компонентах, в `navigationPrefetch` и в карточках
 * фонотеки, и разъехавшиеся копии означали бы промах мимо кэша: префетч по наведению грел бы
 * один ключ запроса, а страница просила другой.
 */

/**
 * Строк в трековых списках за раз: сами треки, избранное, недавние, треки жанра и артиста.
 *
 * Было 100. Список не виртуализирован — `TrackList` рисует все строки разом, — поэтому сотня
 * стоила трижды: коррелированные подзапросы проекции на сервере, сто DTO в канале и сто
 * компонентов в DOM. При высоте строки в 56 пикселей полсотни — это около трёх экранов
 * прокрутки, а пагинация на всех этих страницах и так есть.
 */
export const TRACK_PAGE_SIZE = 50;

/** Карточные сетки альбомов и артистов: у них бесконечная прокрутка, а не пагинация. */
export const CARD_PAGE_SIZE = 60;
